function t(key) {
  return COPY[locale][key] ?? key;
}

function back(to) {
  const arrow = locale === 'ar' ? '→' : '←';
  return `<button type="button" class="back-btn" data-go="${to}" aria-label="back">${arrow}</button>`;
}

function tabBar(active) {
  const tabs = [
    ['home', t('tab.home'), '⌂'],
    ['search', t('tab.search'), '🔍'],
    ['orders', t('tab.orders'), '📦'],
    ['bookings', t('tab.bookings'), '📅'],
    ['profile', t('tab.profile'), '👤'],
  ];
  return `<div class="tab-bar">${tabs
    .map(([id, label, icon]) => {
      const target =
        id === 'home'
          ? 'home'
          : id === 'search'
            ? 'search'
            : id === 'orders'
              ? 'history'
              : id === 'bookings'
                ? 'booking-branch'
                : 'profile';
      return `<button type="button" class="tab-item${id === active ? ' active' : ''}" data-go="${target}"><span>${icon}</span><span>${label}</span></button>`;
    })
    .join('')}</div>`;
}

function restaurantCard(name, meta, badges = '') {
  return `<article class="card-restaurant" data-go="restaurant-detail">
    <div class="thumb" aria-hidden="true"></div>
    <div><h4>${name}</h4><div class="meta">${meta}</div><div style="margin-top:6px;display:flex;gap:6px">${badges}</div></div>
  </article>`;
}

function dishBadgeHtml(badges) {
  const labels = {
    spicy: { en: '🌶 Spicy', ar: '🌶 حار', cls: 'badge-spicy' },
    veg: { en: '🌱 Veg', ar: '🌱 نباتي', cls: 'badge-veg' },
    halal: { en: 'Halal', ar: 'حلال', cls: 'badge-halal' },
  };
  return badges
    .map((b) => {
      const L = labels[b];
      if (!L) return '';
      return `<span class="badge ${L.cls}">${L[locale]}</span>`;
    })
    .join('');
}

function dishCardItem(item) {
  const loc = locale;
  const price = loc === 'ar' ? item.priceAr : item.priceEn;
  const name = item[loc].name;
  const desc = item[loc].desc;
  return `<article class="card-dish" data-dish="${item.id}" role="button" tabindex="0">
    <div class="img" aria-hidden="true"></div>
    <div class="body"><div style="flex:1;min-width:0">
      <strong>${name}</strong>
      <div class="dish-desc">${desc}</div>
      <div class="price">${price}</div>
      <div class="dish-badges">${dishBadgeHtml(item.badges)}</div>
    </div>
    <button type="button" class="add-circle" aria-label="add">+</button></div>
  </article>`;
}

