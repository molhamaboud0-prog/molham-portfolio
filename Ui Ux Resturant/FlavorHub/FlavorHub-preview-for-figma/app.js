function paint() {
  const phoneInner = document.getElementById('phone-screens');
  phoneInner.innerHTML = SCREENS.map((s) => {
    const active = s.id === currentScreen ? ' active' : '';
    return `<section class="screen${active}" id="screen-${s.id}" data-screen="${s.id}">${renderScreen(s.id)}</section>`;
  }).join('');

  document.querySelectorAll('[data-go]').forEach((el) => {
    el.addEventListener('click', (e) => {
      const go = el.getAttribute('data-go');
      if (go) {
        e.stopPropagation();
        navigate(go);
      }
    });
  });

  document.querySelectorAll('[data-menu-cat]').forEach((el) => {
    el.addEventListener('click', (e) => {
      e.stopPropagation();
      menuCategory = el.getAttribute('data-menu-cat');
      const list = document.querySelector('#screen-menu .menu-list');
      if (list) list.innerHTML = renderMenuItemsList();
      document.querySelectorAll('[data-menu-cat]').forEach((chip) => {
        chip.classList.toggle('chip-active', chip.getAttribute('data-menu-cat') === menuCategory);
      });
      bindDishPickers();
    });
  });

  bindDishPickers();

  document.querySelectorAll('[data-qty]').forEach((btn) => {
    btn.addEventListener('click', (e) => {
      e.stopPropagation();
      dishQty = Math.max(1, dishQty + (btn.getAttribute('data-qty') === '+' ? 1 : -1));
      const lbl = document.getElementById('dish-qty-label');
      if (lbl) {
        lbl.textContent =
          locale === 'ar' ? String(dishQty).replace(/\d/g, (d) => '٠١٢٣٤٥٦٧٨٩'[d]) : String(dishQty);
      }
    });
  });

  updateHint();
}

function bindDishPickers() {
  document.querySelectorAll('.card-dish[data-dish]').forEach((el) => {
    el.addEventListener('click', () => {
      selectedDishId = el.getAttribute('data-dish');
      currentScreen = 'dish-detail';
      paint();
    });
  });
}

function updateHint() {
  const screen = SCREENS.find((s) => s.id === currentScreen);
  const hint = document.getElementById('flow-hint');
  if (hint && screen) {
    hint.innerHTML = `<strong>${screen.label}</strong><br>Frame 393×852 · ${locale.toUpperCase()} · ${theme}<br>See <code>prototype/FLOWS.md</code> for Figma prototype mapping.`;
  }
}

function navigate(id) {
  currentScreen = id;
  document.querySelectorAll('.screen').forEach((sec) => {
    sec.classList.toggle('active', sec.dataset.screen === id);
  });
  document.querySelectorAll('.sidebar nav button').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.screen === id);
  });
  updateHint();
}

function initSidebar() {
  const nav = document.getElementById('screen-nav');
  nav.innerHTML = SCREENS.map(
    (s) => `<button type="button" data-screen="${s.id}" class="${s.id === currentScreen ? 'active' : ''}">${s.label}</button>`
  ).join('');
  nav.addEventListener('click', (e) => {
    const btn = e.target.closest('button[data-screen]');
    if (btn) navigate(btn.dataset.screen);
  });
}

function initControls() {
  document.getElementById('btn-en').addEventListener('click', () => {
    locale = 'en';
    document.body.classList.remove('rtl');
    document.body.classList.add('ltr');
    paint();
  });
  document.getElementById('btn-ar').addEventListener('click', () => {
    locale = 'ar';
    document.body.classList.remove('ltr');
    document.body.classList.add('rtl');
    paint();
  });
  document.getElementById('btn-light').addEventListener('click', () => {
    theme = 'light';
    document.documentElement.removeAttribute('data-theme');
    paint();
  });
  document.getElementById('btn-dark').addEventListener('click', () => {
    theme = 'dark';
    document.documentElement.setAttribute('data-theme', 'dark');
    paint();
  });
  document.getElementById('btn-flow-order').addEventListener('click', () => navigate('splash'));
  document.getElementById('btn-flow-book').addEventListener('click', () => navigate('booking-branch'));
}

document.body.classList.add('ltr');
