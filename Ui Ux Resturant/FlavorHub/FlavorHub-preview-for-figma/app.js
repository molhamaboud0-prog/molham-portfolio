function renderDishOptions(dish) {
  const loc = locale;
  const sizes =
    loc === 'ar'
      ? ['عادي', 'كبير', 'وجبة']
      : ['Regular', 'Large', 'Meal deal'];
  const spice = loc === 'ar' ? ['خفيف', 'متوسط', 'حار'] : ['Mild', 'Medium', 'Hot'];
  const sauces =
    loc === 'ar'
      ? ['مايونيز', 'باربيكيو', 'ثوم', 'كاتشب']
      : ['Garlic mayo', 'BBQ', 'Toum', 'Ketchup'];
  const sides =
    loc === 'ar'
      ? ['بطاطس', 'سلطة', 'حلقات بصل', 'بدون']
      : ['Fries', 'Side salad', 'Onion rings', 'None'];
  const drinks =
    loc === 'ar' ? ['بدون', 'كولا', 'ماء', 'عصير'] : ['None', 'Cola', 'Water', 'Juice'];

  const chipGroup = (options, activeIdx = 0) =>
    `<div class="option-chips">${options
      .map((opt, i) => `<button type="button" class="chip${i === activeIdx ? ' chip-active' : ''}">${opt}</button>`)
      .join('')}</div>`;

  return `
    <div class="option-group"><h4>${t('dish.size')}</h4>${chipGroup(sizes, 0)}</div>
    <div class="option-group"><h4>${t('dish.spice')}</h4>${chipGroup(spice, 1)}</div>
    <div class="option-group"><h4>${t('dish.sauces')}</h4>${chipGroup(sauces, 0)}</div>
    <div class="option-group"><h4>${t('dish.sides')}</h4>${chipGroup(sides, 0)}</div>
    <div class="option-group"><h4>${t('dish.drinks')}</h4>${chipGroup(drinks, 0)}</div>
    <div class="modifier"><span>${loc === 'ar' ? 'جبن إضافي' : 'Extra cheese'}</span><input type="checkbox" /></div>
    <div class="modifier"><span>${loc === 'ar' ? 'بدون بصل' : 'No onion'}</span><input type="checkbox" /></div>
    <div class="qty-row"><span>${t('dish.qty')}</span>
      <div class="qty-stepper"><button type="button" data-qty="-">−</button><span id="dish-qty-label">${dishQty}</span><button type="button" data-qty="+">+</button></div>
    </div>
  `;
}

